import { arrowUpFrames, importingFrames } from "./demos/flip-dot-matrix";
import type { Frame, FrameDot, Frames } from "./flip-dot-matrix";

export type DotAnimation = {
  // Milliseconds per frame
  duration: number;
  // Times it plays per like, when it shouldn't use the default
  loops?: number;
  frames: Frames;
};

export const GRID_SIZE: [number, number] = [5, 5];

// Rows separated by "/", "#" is a lit dot
const mask = (rows: string): Frame =>
  rows
    .split("/")
    .flatMap((row, y) =>
      [...row].flatMap((char, x): FrameDot[] => (char === "#" ? [[x, y]] : [])),
    );

const masks = (frames: string[]): Frames => frames.map(mask);

